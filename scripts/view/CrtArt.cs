using Godot;

namespace NSP.View;

// CRT 화면에 올리는 **캐릭터 원화**의 밝기를 한 곳에서 정한다.
//
// 원화는 밝은 파스텔(하늘색 · 연보라 · 흰 옷 · 흰 바탕)로 그려져 있다. 모니터 화면은
// 자기발광(crt_screen 의 EMISSION)이라 그 위에 WorldEnvironment 의 번짐(Glow)과
// 전역 아날로그 LUT 가 차례로 얹힌다. 셋이 겹치면 연한 면이 전부 한 덩어리로 날아가
// **누구 얼굴인지 알아볼 수 없게 된다** — 화면에서 가장 밝은 자리가 되어 번짐까지 먹는다.
//
// 그래서 원화만 조금 눌러서 올린다. 검은 선화는 원래 어두워 거의 그대로 남고
// **연한 면만 내려가므로 대비가 오히려 산다.** 색을 바꾸는 것이 아니라 밝기만 낮춘다
// — 캐릭터 색이 달라 보이면 안 된다.
//
// 세기를 바꾸려면 아래 한 줄만 고친다. 1.0 = 예전(누르지 않음).
public static class CrtArt
{
    // 모니터 화면에 올리는 원화에 곱하는 색.
    public static readonly Color Tint = new(0.66f, 0.70f, 0.74f);

    // 원화 뒤에 까는 어두운 받침 — 눌러서 어두워진 그림이 화면 바탕에 묻히지 않게.
    public static readonly Color Backing = new(0.04f, 0.05f, 0.07f, 0.85f);
}
